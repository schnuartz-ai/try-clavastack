import { chromium } from 'playwright';
import { strict as assert } from 'node:assert';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { BIP32Factory } from 'bip32';
import * as ecc from 'tiny-secp256k1';
import * as bip39 from 'bip39';
import bs58check from 'bs58check';
import { payments, Psbt } from 'bitcoinjs-lib';

const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:8765';
const resultPrefix = `test-results/specter-workflows-${new URL(base).protocol.slice(0, -1)}`;
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ ...(process.env.CI ? {} : { channel: 'chrome' }), headless: true,
  args: base.startsWith('https://127.0.0.1:') ? ['--ignore-certificate-errors'] : [] });
const page = await browser.newPage({ viewport: { width: 1512, height: 1100 } });
const errors = [];
const checks = [];
const diagnostics = [];
const broadcastRequests = [];
page.on('request', request => {
  if (request.url().endsWith('/api/ab/electrum') && request.postData()?.includes('blockchain.transaction.broadcast')) {
    broadcastRequests.push(request.postData());
  }
});
page.on('console', message => { if (message.type() === 'error') diagnostics.push(message.text()); });
const testRoot = BIP32Factory(ecc).fromSeed(bip39.mnemonicToSeedSync(
  'abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about',
  'ClavaStack public browser audit'));
assert.equal(testRoot.fingerprint.toString('hex'), '2ee2ab10');
page.on('pageerror', error => errors.push(error.message));
async function pass(name) { checks.push(name); console.log(`PASS ${name}`); }
try {
  await page.goto(`${base}/specter-desktop/`);
  await page.locator('#desktop-status').getByText('Running locally', { exact: true }).waitFor({ timeout: 360000 });
  await page.locator('#diy-status').getByText('Running locally', { exact: true }).waitFor({ timeout: 90000 });
  await page.frameLocator('#desktop-app').getByRole('link', { name: 'Electrum Connection', exact: true }).waitFor({ timeout: 60000 });
  const app = page.frames().find(frame => frame.url().includes('/specter-desktop/spc/'));
  assert(app, 'Specter Flask frame missing');
  await app.getByRole('link', { name: 'Electrum Connection', exact: true }).click();
  await app.locator('#server-list').selectOption('electrum.blockstream.info');
  await app.getByRole('button', { name: 'Connect', exact: true }).click();
  await app.getByText('Specter is connected via Spectrum to a public Electrum server!', { exact: true }).waitFor({ timeout: 90000 });
  await pass('Blockstream Electrum TLS connection in the real Spectrum extension');

  const diy = page.frames().find(frame => frame.url().includes('variant=diy'));
  await diy.goto(`${base}/?embedded=1&gallery=1&variant=diy&qr-bridge=1&probe=usb-wallet`);
  await diy.waitForFunction(() => document.querySelector('#debug-log')?.textContent.includes('USB_WALLET_PROBE_READY'), null, { timeout: 90000 });
  await page.locator('#cable-toggle').check();
  await page.locator('.cable-panel.connected').waitFor({ timeout: 20000 });
  await app.goto(`${base}/specter-desktop/app/spc/devices/new_device_keys/specter/`);
  const enumeration = await app.evaluate(() => window.hwi.enumerate('', false));
  assert(enumeration.some(device => device.type === 'specter' && device.fingerprint === '2ee2ab10'), JSON.stringify(enumeration));
  await pass('Real DIY USBHost and XpubApp return the test seed fingerprint');
  await app.locator('#device_name').fill('Audit DIY');
  await app.locator('#connect-hwi').click();
  await app.waitForFunction(() => Array.from(document.querySelectorAll('input[id$="-xpub-hidden"]'))
    .filter(input => input.value.startsWith('[2ee2ab10/')).length === 4, null, { timeout: 90000 });
  const accountKeys = await app.locator('input[id$="-xpub-hidden"]').evaluateAll(inputs => inputs.map(input => input.value).filter(value => value.startsWith('[2ee2ab10/')));
  for (const key of accountKeys) {
    const parsed = key.match(/^\[2ee2ab10\/([^\]]+)\]\s*(\S+)\s*$/);
    assert(parsed, JSON.stringify(key));
    const [, path, encoded] = parsed;
    const expected = testRoot.derivePath(`m/${path.replaceAll('h', "'")}`).neutered().toBase58();
    assert.deepEqual(bs58check.decode(encoded).subarray(4), bs58check.decode(expected).subarray(4));
  }
  await pass('All four account keys imported through the real USB firmware protocol');
  await app.getByRole('button', { name: 'Continue', exact: true }).click();
  await app.waitForURL(/\/devices\/device\/audit_diy\//, { timeout: 60000 });
  assert(!await app.getByText('Session expired', { exact: false }).count());
  await pass(`${new URL(base).protocol} Continue creates and saves the device without a CSRF error`);
  await app.locator('#new_device_popup').getByText('Close', { exact: true }).click();
  await app.getByRole('link', { name: 'Add wallet', exact: true }).click();
  await app.getByRole('link', { name: 'Single Signature', exact: true }).click();
  await app.locator('#audit_diy').click();
  await app.locator('#wallet_name').fill('Audit Native');
  await app.getByRole('button', { name: 'Create wallet', exact: true }).click();
  await app.waitForURL(/\/wallet\/audit_native\//, { timeout: 240000 });
  await pass('Single signature wallet created and synchronised through Spectrum');
  await app.getByText('Skip', { exact: true }).click();
  await app.getByRole('link', { name: 'Receive', exact: true }).click();
  await app.locator('#address_qr').waitFor();
  const receive = await app.locator('#address_qr').getAttribute('value');
  const expectedReceive = payments.p2wpkh({ pubkey: testRoot.derivePath("m/84'/0'/0'/0/0").publicKey }).address;
  assert.equal(receive, `bitcoin:${expectedReceive}`);
  await pass('Receive shows an actual mainnet address and QR');
  await app.getByRole('button', { name: 'Get new address', exact: true }).click();
  await app.waitForFunction(previous => document.querySelector('#address_qr')?.getAttribute('value') !== previous, receive);
  const expectedNext = payments.p2wpkh({ pubkey: testRoot.derivePath("m/84'/0'/0'/0/1").publicKey }).address;
  assert.equal(await app.locator('#address_qr').getAttribute('value'), `bitcoin:${expectedNext}`);
  await pass('New address advances to the independently derived BIP84 address');
  const feeResponsePending = page.waitForResponse(response => /\/fees(?:\?|$)/.test(response.url()), { timeout: 60000 });
  await app.getByRole('link', { name: 'Send', exact: true }).click();
  await app.locator('body').getByText('Send', { exact: true }).first().waitFor();
  const feeResponse = await feeResponsePending;
  assert(feeResponse.ok());
  const feeEstimate = await feeResponse.json();
  assert(Number.isFinite(feeEstimate.result.fastestFee) && feeEstimate.result.fastestFee > 0);
  assert(Array.isArray(feeEstimate.error_messages));
  assert(!await app.locator('body').innerText().then(text => text.includes('Failed to fetch fees: SyntaxError')));
  await pass('The native fee API returns parseable JSON without injected HTML');
  await pass('Send page opens for the test wallet');
  await app.locator('#btn_settings').click();
  await app.getByRole('button', { name: 'Export', exact: true }).click();
  await app.waitForFunction(() => document.querySelector('#export_specter_format')?.getAttribute('href')?.startsWith('data:'));
  const backupJson = await app.locator('#export_specter_format').getAttribute('href');
  assert.equal(JSON.parse(decodeURIComponent(backupJson.split(',')[1])).name, 'Audit Native');
  await pass('Wallet backup contains the real saved wallet descriptor');
  await page.locator('#sd-token').click();
  await page.locator('[data-media-target="desktop"]').click();
  const deviceExport = app.getByRole('link', { name: 'Save Audit DIY file', exact: true });
  const exportName = await deviceExport.getAttribute('download');
  const exportBytes = decodeURIComponent((await deviceExport.getAttribute('href')).split(',')[1]);
  assert(exportBytes.includes('2ee2ab10'), 'DIY wallet export must contain the native key origin');
  await deviceExport.click();
  await page.locator('#sd-files').getByText(exportName, { exact: false }).waitFor();
  await app.locator('#export_specter_format').click();
  await page.locator('#sd-files').getByText('Audit Native.json', { exact: false }).waitFor();
  await pass('Native DIY wallet descriptor and Specter backup save on the shared SD card');
  await page.locator('#sd-token').click();
  await page.locator('#sd-token').click();
  await page.locator('[data-media-target="diy"]').click();
  await page.locator('#sd-refresh').click();
  const sdDownload = page.waitForEvent('download');
  await page.locator('#sd-files li').filter({ hasText: exportName }).getByRole('button', { name: 'Download', exact: true }).click();
  const sdFile = await sdDownload;
  const transferred = await readFile(await sdFile.path(), 'utf8');
  assert.equal(transferred, exportBytes);
  await writeFile('test-results/public-diy-wallet.txt', transferred);
  await pass('The same descriptor reaches the real DIY MEMFS and survives an SD snapshot');
  await page.locator('#sd-token').click();
  await page.locator('#sd-location').getByText('Not inserted', { exact: true }).waitFor();
  await page.locator('#sd-token').click();
  await page.locator('[data-media-target="desktop"]').click();
  const signingPath = "m/84'/0'/0'/0/0";
  const signingKey = testRoot.derivePath(signingPath);
  const synthetic = new Psbt();
  synthetic.addInput({ hash: 'ab'.repeat(32), index: 0,
    witnessUtxo: { script: payments.p2wpkh({ pubkey: signingKey.publicKey }).output, value: 100000 },
    bip32Derivation: [{ masterFingerprint: testRoot.fingerprint, path: signingPath, pubkey: signingKey.publicKey }] });
  synthetic.addOutput({ address: expectedNext, value: 99000 });
  synthetic.signInput(0, { publicKey: signingKey.publicKey, sign: hash => Buffer.from(ecc.sign(hash, signingKey.privateKey)) });
  assert(synthetic.validateSignaturesOfInput(0, (pubkey, hash, signature) => ecc.verify(hash, pubkey, signature)));
  await page.locator('#sd-picker').setInputFiles({ name: 'synthetic-signed.psbt', mimeType: 'application/psbt', buffer: synthetic.toBuffer() });
  await page.locator('#sd-files').getByText('synthetic-signed.psbt', { exact: false }).waitFor();
  await app.getByRole('link', { name: 'Send', exact: true }).click();
  await app.getByRole('link', { name: 'Import', exact: true }).click();
  await app.locator('#psbt-uploader').getByRole('button', { name: 'Open a file from the virtual SD card', exact: true }).click();
  await app.getByRole('dialog').getByRole('button', { name: /^synthetic-signed\.psbt/ }).click();
  await app.waitForFunction(expected => document.querySelector('#rawpsbt')?.value === expected, synthetic.toBase64());
  await pass('The upstream shadow-root file picker imports binary PSBT bytes from the virtual SD card');
  await app.getByRole('button', { name: 'Import transaction', exact: true }).click();
  await app.locator('#ready_container').getByText('Transaction is ready to send', { exact: false }).waitFor({ timeout: 60000 });
  const imported = JSON.parse(await app.locator('input[name="pending_psbt"]').inputValue());
  assert.equal(imported.tx.vin[0].txid, 'ab'.repeat(32));
  assert.equal(Math.round(imported.fee * 1e8), 1000);
  assert(imported.raw, 'Upstream Spectrum must finalize the imported signature');
  assert.deepEqual(broadcastRequests, []);
  await pass('Native Spectrum finalizes the signed synthetic PSBT without broadcasting');
  await page.screenshot({ path: `${resultPrefix}-synthetic-import.png`, fullPage: true });
  await app.getByRole('link', { name: 'Settings', exact: true }).first().click();
  await app.locator('select[name="unit"]').selectOption('sat');
  await app.getByRole('button', { name: 'Save', exact: true }).click();
  assert.equal(await app.locator('select[name="unit"]').inputValue(), 'sat');
  await pass('General settings save successfully');
  const downloaded = page.waitForEvent('download');
  await app.getByRole('link', { name: 'Backup Specter (Zip File)', exact: true }).click();
  const backup = await downloaded;
  assert.equal(backup.suggestedFilename().endsWith('.zip'), true);
  assert.equal(await backup.failure(), null);
  await pass('Full Specter backup downloads successfully');
  await page.reload();
  await page.locator('#desktop-status').getByText('Running locally', { exact: true }).waitFor({ timeout: 360000 });
  await page.frameLocator('#desktop-app').getByRole('link', { name: /^Audit Native/ }).waitFor({ timeout: 60000 });
  await pass('Wallet, device, node and local database survive a reload');
  await page.screenshot({ path: `${resultPrefix}-online.png`, fullPage: true });
  await page.route('**/api/ab/electrum', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Test server outage' }) }));
  await page.reload();
  await page.locator('#desktop-status').getByText('Running locally', { exact: true }).waitFor({ timeout: 360000 });
  await page.frameLocator('#desktop-app').getByRole('link', { name: /^Audit Native/ }).waitFor({ timeout: 60000 });
  await pass('An unavailable Electrum relay does not prevent Desktop startup or hide saved wallets');
  await page.screenshot({ path: `${resultPrefix}-offline.png`, fullPage: true });
  await page.unroute('**/api/ab/electrum');
  await page.frameLocator('#desktop-app').getByRole('link', { name: /^Audit Native/ }).click();
  await page.frameLocator('#desktop-app').locator('#active-node').getByText('Bitcoin Network', { exact: true }).waitFor({ timeout: 60000 });
  await pass('A saved wallet reconnects to the actual Electrum server after the relay returns');
  assert.deepEqual(errors, []);
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: `${resultPrefix}-reconnected.png`, fullPage: true });
} catch (error) {
  console.error(await page.frameLocator('#desktop-app').locator('body').innerText().catch(() => 'No Desktop frame'));
  console.error(await page.frameLocator('#diy-app').locator('#debug-log').textContent().catch(() => 'No DIY log'));
  await page.screenshot({ path: `${resultPrefix}-failure.png`, fullPage: true }).catch(() => {});
  throw error;
} finally {
  await mkdir('test-results', { recursive: true });
  await writeFile(`${resultPrefix}.json`, JSON.stringify({ base, checks, errors, diagnostics, broadcastRequests }, null, 2));
  await browser.close();
}
